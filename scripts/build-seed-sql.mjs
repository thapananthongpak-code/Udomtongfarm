// Writes supabase/seed.sql from src/data/species.ts, src/data/menu.ts and src/data/services.ts.
// Run with `npm run db:seed-sql` after editing any of them.

import { writeFileSync } from "node:fs";
import { seedMenu as menu } from "../src/data/menu.ts";
import { seedServices as services } from "../src/data/services.ts";
import { seedSpecies as species } from "../src/data/species.ts";

const text = (value) => (value === null || value === undefined ? "null" : `'${String(value).replaceAll("'", "''")}'`);
const textArray = (values) => (values.length ? `array[${values.map(text).join(", ")}]` : "'{}'");

const COLUMNS = [
  "id", "type", "name_th", "name_en", "scientific_name", "status",
  "summary_th", "summary_en", "body_th", "body_en", "image", "tags", "sources", "featured", "published",
];

const rows = species.map(
  (sp) =>
    `  (${[
      text(sp.id), text(sp.type), text(sp.name_th), text(sp.name_en), text(sp.scientific_name), text(sp.status),
      text(sp.summary_th), text(sp.summary_en), text(sp.body_th), text(sp.body_en), text(sp.image),
      textArray(sp.tags), `${text(JSON.stringify(sp.sources))}::jsonb`, sp.featured, sp.published,
    ].join(", ")})`,
);

const MENU_COLUMNS = ["category", "name_th", "name_en", "description_th", "description_en", "sort_order"];

const menuRows = menu.map(
  (item) =>
    `    (${[
      text(item.category), text(item.name_th), text(item.name_en),
      text(item.description_th), text(item.description_en), item.sort_order,
    ].join(", ")})`,
);

const SERVICE_COLUMNS = ["kind", "name_th", "name_en", "description_th", "description_en", "price", "sort_order"];

const serviceRows = services.map(
  (item) =>
    `    (${[
      text(item.kind), text(item.name_th), text(item.name_en),
      text(item.description_th), text(item.description_en),
      item.price === null ? "null::integer" : item.price, item.sort_order,
    ].join(", ")})`,
);

const sql = `-- Loads the starting collection (${species.length} species). Generated by scripts/build-seed-sql.mjs.
-- Run after schema.sql. Species that already exist are left unchanged, so edits made on the site are kept.

insert into public.species (${COLUMNS.join(", ")})
values
${rows.join(",\n")}
on conflict (id) do nothing;

-- Loads the sample café menu (${menu.length} items), only while the menu is still empty.
-- Once the café has entered its own menu, running this again adds nothing.

insert into public.menu_items (${MENU_COLUMNS.join(", ")})
select *
from (
  values
${menuRows.join(",\n")}
) as sample (${MENU_COLUMNS.join(", ")})
where not exists (select 1 from public.menu_items);

-- Loads the farm's activities and rates (${services.length} lines), only while that list is still empty.
-- Prices are left empty except where the farm has said something is free.

insert into public.farm_services (${SERVICE_COLUMNS.join(", ")})
select *
from (
  values
${serviceRows.join(",\n")}
) as sample (${SERVICE_COLUMNS.join(", ")})
where not exists (select 1 from public.farm_services);
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(
  `Wrote supabase/seed.sql with ${species.length} species, ${menu.length} menu items and ${services.length} services.`,
);
